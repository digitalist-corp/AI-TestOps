-- =====================================================================
-- V1__baseline_schema.sql
-- AI-TestOps Baseline Schema (20 core tables + existing tables)
-- Uses CREATE TABLE IF NOT EXISTS so existing databases upgrade cleanly.
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS projects (
    project_id VARCHAR(100) PRIMARY KEY,
    project_name VARCHAR(200) NOT NULL,
    display_order INTEGER DEFAULT 0,
    server_type VARCHAR(20),
    description TEXT,
    test_purpose TEXT,
    manager_name VARCHAR(100),
    manager_contact VARCHAR(200),
    node_version VARCHAR(20) DEFAULT '22',
    playwright_version VARCHAR(20) DEFAULT '1.53.0',
    package_manager VARCHAR(10) DEFAULT 'NPM',
    install_command VARCHAR(500),
    test_command VARCHAR(500),
    working_directory VARCHAR(500),
    env_variables TEXT,
    login_env_required BOOLEAN DEFAULT FALSE,
    login_setup_spec_path VARCHAR(500),
    storage_state_max_age_minutes INTEGER DEFAULT 720,
    timeout INTEGER DEFAULT 300,
    parallel_limit INTEGER DEFAULT 1,
    base_url VARCHAR(500),
    repository_url VARCHAR(500),
    repository_branch VARCHAR(100),
    repository_token_encrypted TEXT,
    source_repository_url VARCHAR(500),
    source_repository_branch VARCHAR(100),
    source_repository_token_encrypted TEXT,
    runner_lifecycle VARCHAR(20) DEFAULT 'PERSISTENT',
    docker_enabled BOOLEAN DEFAULT FALSE,
    docker_container_id VARCHAR(100),
    docker_status VARCHAR(20) DEFAULT 'NOT_CONFIGURED',
    ai_model_provider VARCHAR(20) DEFAULT 'CLAUDE',
    ai_auto_apply_enabled BOOLEAN DEFAULT FALSE,
    ai_auto_apply_max_changed_lines INTEGER DEFAULT 30,
    ai_auto_apply_max_changed_files INTEGER DEFAULT 2,
    ai_allowed_path_globs TEXT,
    ai_denied_path_globs TEXT,
    ai_max_iterations INTEGER DEFAULT 5,
    owner_user_id BIGINT,
    monthly_ai_budget_usd NUMERIC(18, 8) NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    grep_filter VARCHAR(500),
    spec_path VARCHAR(500),
    case_title VARCHAR(500),
    total_tests INTEGER DEFAULT 0,
    passed_tests INTEGER DEFAULT 0,
    failed_tests INTEGER DEFAULT 0,
    skipped_tests INTEGER DEFAULT 0,
    duration_ms BIGINT,
    report_path VARCHAR(500),
    source VARCHAR(30) DEFAULT 'MANUAL',
    sequential BOOLEAN NOT NULL DEFAULT FALSE,
    log_output TEXT,
    error_message TEXT,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    schedule_id BIGINT,
    scheduled_for TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS execution_case_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL,
    spec_path VARCHAR(500),
    case_title TEXT,
    status VARCHAR(20) NOT NULL,
    duration_ms INTEGER,
    error_message TEXT,
    attempt_index INTEGER NOT NULL DEFAULT 0,
    case_index INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS test_suites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,
    spec_paths TEXT,
    grep TEXT,
    case_count INTEGER DEFAULT 0,
    sequential BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS execution_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    name VARCHAR(200),
    suite_id BIGINT,
    spec_path VARCHAR(500),
    case_title VARCHAR(500),
    hour INTEGER NOT NULL DEFAULT 0,
    minute INTEGER NOT NULL DEFAULT 0,
    days_of_week VARCHAR(50) NOT NULL DEFAULT '*',
    cron_expression VARCHAR(100),
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Seoul',
    run_at TIMESTAMP WITH TIME ZONE,
    next_run_at TIMESTAMP WITH TIME ZONE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    misfire_policy VARCHAR(20) NOT NULL DEFAULT 'FIRE_ONCE',
    last_triggered_at TIMESTAMP WITH TIME ZONE,
    created_by BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    job_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    ai_model_provider VARCHAR(20) NOT NULL,
    instruction TEXT,
    target_spec_path VARCHAR(500),
    route_keys TEXT,
    failed_execution_id BIGINT,
    iterations_used INTEGER DEFAULT 0,
    diff_path VARCHAR(500),
    changed_files TEXT,
    summary TEXT,
    risk_flags TEXT,
    error_message TEXT,
    callback_token VARCHAR(100),
    callback_token_expires_at TIMESTAMP WITH TIME ZONE,
    requested_by BIGINT,
    reviewed_by BIGINT,
    rejection_reason VARCHAR(500),
    applied_commit_sha VARCHAR(100),
    post_apply_verification_status VARCHAR(20),
    post_apply_verification_execution_id BIGINT,
    reverted_at TIMESTAMP WITH TIME ZONE,
    revert_commit VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(16) NOT NULL,
    feature VARCHAR(40),
    project_id VARCHAR(100),
    job_id BIGINT,
    request_id VARCHAR(100),
    model VARCHAR(200),
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    input_unit_price NUMERIC(18, 8),
    output_unit_price NUMERIC(18, 8),
    cost_usd NUMERIC(18, 8),
    reserved_usd NUMERIC(18, 8),
    status VARCHAR(20) DEFAULT 'SUCCEEDED',
    usage_estimated BOOLEAN NOT NULL DEFAULT FALSE,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    settled_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS ai_provider_settings (
    id BIGINT PRIMARY KEY,
    claude_api_key_encrypted TEXT,
    openai_api_key_encrypted TEXT,
    claude_workspace_id VARCHAR(255),
    default_provider VARCHAR(16),
    claude_input_price DOUBLE PRECISION,
    claude_output_price DOUBLE PRECISION,
    openai_input_price DOUBLE PRECISION,
    openai_output_price DOUBLE PRECISION,
    claude_transport VARCHAR(30) DEFAULT 'ANTHROPIC',
    bedrock_region VARCHAR(50),
    bedrock_model VARCHAR(200),
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS site_analysis_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    commit_sha VARCHAR(64),
    framework VARCHAR(30),
    partial BOOLEAN NOT NULL DEFAULT FALSE,
    screen_count INTEGER NOT NULL DEFAULT 0,
    processed_count INTEGER DEFAULT 0,
    progress_at TIMESTAMP WITH TIME ZONE,
    llm_calls INTEGER DEFAULT 0,
    warnings TEXT,
    error_message TEXT,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS site_node (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    route_key VARCHAR(500) NOT NULL,
    title VARCHAR(300),
    source_file VARCHAR(700),
    origin VARCHAR(20) NOT NULL DEFAULT 'CODE',
    auth_required BOOLEAN,
    elements TEXT NOT NULL,
    links TEXT,
    content_hash VARCHAR(64),
    first_seen_commit VARCHAR(64),
    last_seen_commit VARCHAR(64),
    stale BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_site_node_route UNIQUE (project_id, route_key)
);

CREATE TABLE IF NOT EXISTS site_edge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    from_route_key VARCHAR(500) NOT NULL,
    to_route_key VARCHAR(500) NOT NULL,
    kind VARCHAR(20) NOT NULL DEFAULT 'LINK',
    label VARCHAR(300),
    selector VARCHAR(700),
    source_file VARCHAR(700),
    source_line INTEGER
);

CREATE TABLE IF NOT EXISTS site_layout (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    source_file VARCHAR(700) NOT NULL,
    route_keys TEXT,
    elements TEXT,
    links TEXT,
    content_hash VARCHAR(64),
    CONSTRAINT uk_site_layout_file UNIQUE (project_id, source_file)
);

CREATE TABLE IF NOT EXISTS site_node_edit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    route_key VARCHAR(500) NOT NULL,
    excluded BOOLEAN NOT NULL DEFAULT FALSE,
    note VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_site_node_edit_route UNIQUE (project_id, route_key)
);

CREATE TABLE IF NOT EXISTS scenario_origin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    spec_path VARCHAR(500) NOT NULL,
    route_keys TEXT,
    selector_keys TEXT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_scenario_origin_spec UNIQUE (project_id, spec_path)
);

CREATE TABLE IF NOT EXISTS scenario_case_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(100) NOT NULL,
    node_type VARCHAR(20) NOT NULL,
    spec_path VARCHAR(500) NOT NULL,
    grep_filter VARCHAR(500) NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_scenario_case_settings_key UNIQUE (project_id, node_type, spec_path, grep_filter)
);

CREATE TABLE IF NOT EXISTS board_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    parent_id BIGINT,
    content TEXT NOT NULL,
    attachments_json TEXT,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    visible_from TIMESTAMP WITH TIME ZONE,
    visible_until TIMESTAMP WITH TIME ZONE,
    created_by VARCHAR(100) NOT NULL,
    updated_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS board_post_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES board_posts(id) ON DELETE CASCADE,
    parent_id BIGINT,
    content TEXT NOT NULL,
    attachments_json TEXT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by VARCHAR(100) NOT NULL,
    updated_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS board_post_reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES board_posts(id) ON DELETE CASCADE,
    username VARCHAR(100) NOT NULL,
    liked BOOLEAN NOT NULL DEFAULT FALSE,
    rating INTEGER,
    memo TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_board_post_reaction_user UNIQUE (post_id, username)
);

CREATE TABLE IF NOT EXISTS user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(100) UNIQUE,
    token_hash VARCHAR(64) UNIQUE,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_accessed_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    user_agent VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS user_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    actor_username VARCHAR(100),
    action VARCHAR(50) NOT NULL,
    target_user_id BIGINT,
    target_username VARCHAR(100),
    project_id VARCHAR(100),
    resource_type VARCHAR(100),
    resource_id VARCHAR(100),
    request_id VARCHAR(100),
    outcome VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    detail TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS slack_settings (
    id BIGINT PRIMARY KEY,
    project_id VARCHAR(100),
    webhook_url_encrypted TEXT,
    event_types TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
