-- 계획 우선 흐름: 계획 행(plan_items)은 테스트가 아직 없어도 있다. spec_path · grep_filter 가 둘 다 NULL 이면 미연결(미작성).
-- 연결 전에는 계획 칸(사용 · 순서 · 담당자 · 마감일 · 우선순위)이 여기 있고, 연결하면 scenario_case_settings TEST 행으로 복사한다.
-- "한 케이스는 한 계획에만 연결"은 H2(테스트)와 같이 돌도록 partial index 없이 서비스에서 검사한다.
-- auto_link: 제목이 같은 테스트에 자동으로 이을지. 사람이 연결을 끊으면 FALSE (다음 조회에 다시 붙지 않도록).
CREATE TABLE plan_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       VARCHAR(100) NOT NULL REFERENCES projects (project_id) ON DELETE CASCADE,
    title            VARCHAR(200) NOT NULL,
    screen_route_key VARCHAR(500),
    expected         TEXT,
    spec_path        VARCHAR(500),
    grep_filter      VARCHAR(500),
    auto_link        BOOLEAN      NOT NULL DEFAULT TRUE,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order       INT,
    assignee         VARCHAR(100),
    assignee_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    due_date         DATE,
    priority         VARCHAR(10),
    ai_job_id        BIGINT REFERENCES ai_jobs (id) ON DELETE SET NULL,
    created_by       BIGINT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by       BIGINT,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_plan_items_project ON plan_items (project_id);
CREATE INDEX idx_plan_items_assignee ON plan_items (assignee_user_id);
