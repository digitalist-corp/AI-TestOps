package com.playops.api.chat;

/**
 * 채팅 도구의 권한 단계. 에이전트 루프는 이 값만 보고 사용자에게 허락을 받을지 정한다.
 */
public enum ToolTier {
    /** 읽기만 한다. 묻지 않고 바로 실행한다. */
    READ,
    /** 테스트 실행처럼 시간이 걸리거나 대상에 영향을 줄 수 있다. 실행 전에 사용자 허락을 받는다. */
    RUN,
    /** 파일을 바꾸는 AI 작업을 만든다. 실제 반영은 사람 승인(NEEDS_REVIEW)을 거치므로 따로 묻지 않는다. */
    CHANGE
}
